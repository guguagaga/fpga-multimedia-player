//===================================================================
// Character ROM (char_rom) -- 8x16 ASCII font, SYNCHRONOUS read (BRAM)
//===================================================================
// Stores 95 printable ASCII chars (0x20 space .. 0x7E ~) as 8x16 dots.
// Each char is 16 bytes (16 rows), each byte 8 bits (8 columns, bit7 =
// leftmost column). Total size = 95 x 16 = 1520 bytes.
//
// addr = {char_index[6:0], row[3:0]} = char_index*16 + row
// char_index = ASCII - 0x20
//
// Synchronous read so the synthesizer maps it into a BRAM (not LUT).
// Font data is loaded from font_8x16.mem (generated by gen_font.py).
//===================================================================
module char_rom (
  input  wire        clk,
  input  wire [10:0] addr,  // char_index*16 + row
  output reg  [ 7:0] dout   // one font row, 8 bits = 8 columns
);

  reg [7:0] rom[0:1519];  // 1520 bytes font

  initial $readmemh("font_8x16.mem", rom);

  always @(posedge clk) dout <= rom[addr];

endmodule
